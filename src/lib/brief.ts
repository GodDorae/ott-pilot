/**
 * 3단계 시작 전 안내 (프로토타입 체험 상황 제시)
 *
 * 이 화면이 이용조건(SVOD/TVOD) 조작을 참여자에게 실제로 전달한다.
 * 자극물 화면에는 TVOD 조건의 '구매' 배지밖에 없어서, 그것만으로는 결제 방식이
 * 무엇인지도 금액이 얼마인지도 알 수 없다. 조절변수가 제대로 걸리려면
 * 자극물을 보기 전에 조건을 글로 한 번 읽어야 한다.
 *
 * 상황 제시문(아래 SCENE)은 두 조건에서 완전히 동일하다.
 * 결제 방식 문장 하나만 갈린다 — 그것이 이 실험의 조절변수다.
 */

import type { UsageCondition } from "./experiment";

export const BRIEF_KICKER = "[프로토타입 체험] 상황";
export const BRIEF_TITLE = "실험 안내";

/** 이용조건별 결제 안내 — 여기만 두 조건에서 다르다 */
export function usageBrief(condition: UsageCondition): string {
  return condition === "TVOD"
    ? "지금부터 보실 추천 화면의 콘텐츠는 개별 대여 콘텐츠로, 5,500원 결제 시 48시간 동안 시청하실 수 있습니다."
    : "지금부터 보실 추천 화면의 콘텐츠는 회원님이 가입한 구독 서비스에 포함되어 있어, 추가 결제 없이 바로 시청하실 수 있습니다.";
}

/**
 * 상황 제시문 — 두 조건 공통.
 *
 * 첫 문장의 기기는 참여자가 실제로 접속한 기기에 맞춘다. 목업 프레임(스마트폰/브라우저 창)과
 * 맥락 인식 조건 문구("스마트폰으로"/"큰 화면으로")가 이미 접속 기기를 따르므로,
 * 안내문만 "모바일 앱"으로 고정하면 PC 참여자에게는 화면과 글이 어긋난다.
 */
export function briefScene(isMobile: boolean): string[] {
  const where = isMobile ? "모바일 OTT 앱에서" : "PC 로 OTT 서비스에 접속해";
  return [
    `당신은 지금 ${where} 볼 콘텐츠를 탐색하고 있는 상황입니다.`,
    "홈 화면을 둘러보던 중 콘텐츠 추천 영역을 발견했습니다.",
    "이후 해당 경험을 바탕으로 이어지는 문항에 응답해 주세요.",
  ];
}
