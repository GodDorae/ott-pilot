-- 측정 도구 판번호를 날짜 표기에서 세는 번호로 — 이전 응답 = 1, 이번 개정 이후 = 2
--
-- 왜: 분석에서 "판 1 응답 / 판 2 응답" 으로 갈라 보게 되는데, 날짜 표기
-- (2026-09-05.a / 09-06.a / 09-07.a)는 판이 셋으로 보여 어느 쪽과 어느 쪽을 합쳐도 되는지가
-- 값만 봐서는 드러나지 않는다. 이번 개정에서 이용조건 조작(금액·기간)과 추천 근거 문구가
-- 함께 바뀌었으므로, 그 앞뒤로만 갈라 보면 된다.
--
-- 판 1 = 개별 대여 5,500원 48시간 · 추천 근거 문구 이전 판
-- 판 2 = 개별 대여 4,000원, 결제 후 30일 내 시청 시작 후 48시간 · 추천 근거 확정 문구
--        (무엇이 바뀌었는지는 src/lib/phase.ts 의 기록에 남겨 두었다)
--
-- 이 마이그레이션을 돌리기 전 실제 응답 35건은 모두 '2026-09-07.a' 였다 — 09-05·09-06
-- 구성으로 받은 행은 남아 있지 않으므로, 판 1 로 합쳐도 잃는 구분이 없다.
--
-- 값 비교로만 걸러서 두 번 돌려도 안전하다.

-- 이번 개정판이 잠깐 날짜 표기로 찍었던 값은 판 2 로
update public.participants
   set instrument_version = '2'
 where instrument_version = '2026-09-09.a';

-- 그 밖의 이전 표기와 빈 값은 모두 판 1 로 (컬럼이 없던 시절의 행은 null 이다)
update public.participants
   set instrument_version = '1'
 where coalesce(instrument_version, '') not in ('1', '2');

comment on column public.participants.instrument_version is
  '응답 수집 당시의 문항 구성 판번호 (src/lib/phase.ts 의 INSTRUMENT_VERSION). 1 = 초판(개별 대여 5,500원 48시간), 2 = 추천 근거 확정 문구 + 개별 대여 4,000원 · 결제 후 30일 내 시청 시작, 시작 후 48시간.';
